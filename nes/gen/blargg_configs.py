#!/usr/bin/env python3
"""Suite configs for blargg ROMs on the console (the `nes` workspace's root).

    python3 nes/gen/blargg_configs.py nes/roms/instr_test-v5/rom_singles/*.nes

Writes nes/tests/blargg/<rom>.json for each NROM (mapper 0) ROM: PRG into
`cart/prg_rom` (16 KiB mirrored), CHR into `cart/chr`, mirroring from the header;
the power-on reset starts the CPU. Run each with
`cargo run --release --example nes_suite -- .gatequest/workspaces/nes <config>`.
"""
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, "../tests/blargg")
os.makedirs(out_dir, exist_ok=True)
for path in sys.argv[1:]:
    h = open(path, "rb").read(16)
    mapper = (h[6] >> 4) | (h[7] & 0xF0)
    if mapper != 0:
        print(f"skip {path}: mapper {mapper}")
        continue
    prg, chr_ = h[4] * 16384, h[5] * 8192
    rel = os.path.relpath(os.path.abspath(path), out_dir)
    start = [{"load": {"part": "cart/prg_rom", "file": rel, "skip": 16, "length": prg, "at": 0}}]
    if prg == 16384:
        start.append({"load": {"part": "cart/prg_rom", "file": rel, "skip": 16, "length": prg, "at": 16384}})
    if chr_:
        start.append({"load": {"part": "cart/chr", "file": rel, "skip": 16 + prg, "length": chr_, "at": 0}})
    cfg = {
        "_comment": f"blargg {os.path.basename(path)} on the console (generated by nes/gen/blargg_configs.py).",
        "kind": "blargg",
        "signals": {"sync": "cpu.sync"},
        "inputs": {"reset": 0, "vertical": h[6] & 1},
        "memory": {"part": "ram", "mask": "0x07FF",
                   "regions": [{"from": "0x6000", "to": "0x7FFF", "part": "cart/prg_ram", "at": 0}]},
        "start": start,
        "boundary": "sync",
        "timing": {"ticks_per_cycle": 3, "sample": 0},
        "status_at": "0x6000",
        "max_cycles": 60000000,
    }
    name = os.path.splitext(os.path.basename(path))[0]
    json.dump(cfg, open(os.path.join(out_dir, name + ".json"), "w"), indent=2)
    print("wrote", name)
